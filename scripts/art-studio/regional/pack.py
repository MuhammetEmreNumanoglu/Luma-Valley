# Pack the original regional sprites (regional.js) into assets/art and write src/art/regional.generated.ts.
# usage: python3 pack.py <render-out-dir> <repo-root>
import json, os, sys
from PIL import Image
OUT, APP = sys.argv[1], sys.argv[2]
meta = json.load(open(f'{OUT}/_meta.json'))
# Target width (Kenney grid units) of the restored sprite; every stage of one model shares its scale.
TARGET = {'landmark': 3.0, 'crossing': 3.4, 'tree': None, 'prop': 1.5}
TREE_H = 2.3
def crop(name):
    # postfx.py writes name.fx.png at half the render size (2x supersampled), so anchor and unit halve too.
    im = Image.open(f'{OUT}/{name}.fx.png').convert('RGBA')
    ax, ay = (v / 2 for v in meta[name]['anchor']); unit = meta[name]['unitPx'] / 2
    a = im.getchannel('A').point(lambda v: 255 if v > 6 else 0)
    x0, y0, x1, y1 = a.getbbox()
    x0 = max(0, x0 - 2); y0 = max(0, y0 - 2); x1 = min(im.width, x1 + 2); y1 = min(im.height, y1 + 2)
    return im.crop((x0, y0, x1, y1)), ax - x0, ay - y0, unit
reg = {}
groups = {}
for name in meta:
    base, kind = (name.rsplit('_', 1)[0], name.split('_')[2]) if name[-1].isdigit() else (name, name.split('_')[2])
    groups.setdefault(base, []).append(name)
for base, names in sorted(groups.items()):
    kind = base.split('_')[2]
    ref = sorted(names)[-1]
    im, ax, ay, unit = crop(ref)
    if kind == 'tree':
        f = TREE_H / (im.height / unit)
    else:
        f = TARGET[kind] / (im.width / unit)
    for n in names:
        im, ax, ay, unit = crop(n)
        os.makedirs(f'{APP}/assets/art/regional', exist_ok=True)
        im.save(f'{APP}/assets/art/regional/{n}.png', optimize=True)
        reg[n] = (im.width, im.height, round(ax, 1), round(ay, 1), round(unit / f, 2))
lines = ['// Generated by scripts/art-studio/regional/pack.py. Do not edit by hand.',
         '// Original procedural three.js models (scripts/art-studio/regional/regional.js); see docs/ORIGINAL_REGION_ART.md.',
         "import type { ArtSprite } from './registry.generated';",
         'export const REGIONAL_ART: Record<string, ArtSprite> = {']
for n, (w, h, ax, ay, u) in sorted(reg.items()):
    lines.append(f"  '{n}': {{ src: require('../../assets/art/regional/{n}.png'), w: {w}, h: {h}, ax: {ax}, ay: {ay}, unit: {u} }},")
lines.append('};')
open(f'{APP}/src/art/regional.generated.ts', 'w').write('\n'.join(lines) + '\n')
man = json.load(open(f'{APP}/assets/art/manifest.json'))
man = [m for m in man if not m['id'].startswith('regional_r')]
for n, (w, h, ax, ay, u) in sorted(reg.items()):
    man.append({'id': n, 'category': 'regional', 'file': f'assets/art/regional/{n}.png', 'size': [w, h], 'anchor': [ax, ay], 'pxPerUnit': u,
                'source': 'Original procedural 3D model by this project (scripts/art-studio/regional/regional.js), rendered with three.js (MIT)', 'license': 'Original work, project-owned'})
open(f'{APP}/assets/art/manifest.json', 'w').write(json.dumps(man, indent=2, ensure_ascii=False) + '\n')
print(len(reg))
