# Trim/anchor rendered sprites, write assets/art/* and src/art/registry.generated.ts
import json, os, sys
from PIL import Image
APP = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/app'
# Hand-authored replacements must not be silently overwritten by a studio rebuild.
manifest_path = os.path.join(APP, 'assets', 'art', 'manifest.json')
existing = {entry['id']: entry for entry in json.load(open(manifest_path, encoding='utf8'))} if os.path.exists(manifest_path) else {}
protected = {key for key, entry in existing.items() if entry.get('license') == 'OpenAI-generated; not represented as CC0'}
srcs = [('out_items', 'items'), ('out_st', None), ('out_ui', None), ('outp2', None)]
reg = {}
for d, _ in srcs:
    meta = json.load(open(f'/home/claude/studio/{d}/_meta.json'))
    for name, mt in sorted(meta.items()):
        if name in protected and name in existing:
            old = existing[name]
            reg[name] = (name, old['category'], old['size'][0], old['size'][1], old['anchor'][0], old['anchor'][1], old['pxPerUnit'])
            continue
        im = Image.open(f'/home/claude/studio/{d}/{name}.png').convert('RGBA')
        if name.startswith('item_'): cat = 'items'
        elif name.startswith('icon_'): cat = 'icons'
        elif name.startswith('portrait_'): cat = 'portraits'
        elif name.startswith('producer_'): cat = 'producers'
        elif name.startswith('st_'): cat = 'structures'
        else: cat = 'props'
        ax, ay = mt.get('anchor', [im.width / 2, im.height]); unit = mt.get('unitPx', 1)
        if cat in ('items', 'producers', 'icons'):
            # Trim to the object (+ shadow) and re-centre on a square so every item fills its cell alike.
            a = im.getchannel('A').point(lambda v: 255 if v > 10 else 0)
            bb = a.getbbox()
            if bb:
                x0, y0, x1, y1 = bb
                side = int(max(x1 - x0, y1 - y0) * 1.06) + 2
                sq = Image.new('RGBA', (side, side), (0, 0, 0, 0))
                ox = (side - (x1 - x0)) // 2; oy = (side - (y1 - y0)) // 2
                sq.paste(im.crop(bb), (ox, oy))
                k = 256 / side
                ax = (ax - x0 + ox) * k; ay = (ay - y0 + oy) * k; unit *= k
                T = 128 if cat == 'icons' else 256
                k2 = T / 256; ax *= k2; ay *= k2; unit *= k2
                im = sq.resize((T, T), Image.LANCZOS)
        if cat in ('structures', 'props'):
            a = im.getchannel('A').point(lambda v: 255 if v > 6 else 0)
            bb = a.getbbox()
            if bb:
                x0, y0, x1, y1 = bb
                x0 = max(0, x0 - 2); y0 = max(0, y0 - 2); x1 = min(im.width, x1 + 2); y1 = min(im.height, y1 + 2)
                im = im.crop((x0, y0, x1, y1)); ax -= x0; ay -= y0
        if cat == 'portraits':
            im = im.resize((256, 256), Image.LANCZOS); ax = 128; ay = 256; unit = 1
        os.makedirs(f'{APP}/assets/art/{cat}', exist_ok=True)
        im.save(f'{APP}/assets/art/{cat}/{name}.png', optimize=True)
        reg[name] = (name, cat, im.width, im.height, round(ax, 1), round(ay, 1), round(unit, 2))
for name in protected - reg.keys():
    old = existing[name]
    reg[name] = (name, old['category'], old['size'][0], old['size'][1], old['anchor'][0], old['anchor'][1], old['pxPerUnit'])
lines = ['// Generated by the art studio (scripts/art-studio). Do not edit by hand.',
         '// Kenney CC0 3D kits rendered to isometric PNG sprites; see docs/ASSET_LICENSES.md.',
         '/* eslint-disable */',
         'export interface ArtSprite { src: number; w: number; h: number; ax: number; ay: number; unit: number }',
         'export const ART: Record<string, ArtSprite> = {']
for n, c, w, h, ax, ay, u in sorted(reg.values()):
    lines.append(f"  '{n}': {{ src: require('../../assets/art/{c}/{n}.png'), w: {w}, h: {h}, ax: {ax}, ay: {ay}, unit: {u} }},")
lines.append('};')
open(f'{APP}/src/art/registry.generated.ts', 'w').write('\n'.join(lines) + '\n')
SRC = {'portraits': 'Kenney Mini Characters (CC0), recoloured; expression rig original (scripts/art-studio/portrait.html)', 'icons': 'Original 3D models (scripts/art-studio/custom.js) and Kenney kits (CC0)', '*': 'Kenney 3D kits (kenney.nl, CC0) and original models (custom.js), rendered by scripts/art-studio'}
man = [{'id': n, 'category': c, 'file': f'assets/art/{c}/{n}.png', 'size': [w, h], 'anchor': [ax, ay], 'pxPerUnit': u,
        'source': SRC.get(c, SRC['*']), 'license': 'CC0 1.0'} for n, c, w, h, ax, ay, u in sorted(reg.values())]
for entry in man:
    if entry['id'] in protected and entry['id'] in existing:
        entry['source'] = existing[entry['id']]['source']
        entry['license'] = existing[entry['id']]['license']
json.dump(man, open(f'{APP}/assets/art/manifest.json', 'w'), indent=1)
print(len(reg))
