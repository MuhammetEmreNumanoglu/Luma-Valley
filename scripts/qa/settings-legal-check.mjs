// Settings → Legal and support: privacy policy and open-source licenses open and read offline.
import { createRequire } from 'node:module';
import { newGame } from '../../src/engine/state.ts';
import { encode } from '../../src/persistence/save.ts';
import { QUEST } from '../../src/content/quests.ts';
const { chromium } = createRequire(import.meta.url)('playwright-core');
const out = process.argv[2] ?? 'e2e-out';
const now = Date.now(), s = newGame(now, 2, 0);
s.flags = { introDone: true, tutMerge: true, tutProduce: true, tutFive: true, tutStarCoin: true };
s.settings.lang = 'tr'; s.quests.seen = Object.keys(QUEST); s.tutorial.skipped = true;
const save = encode(s, 1, now);
const browser = await chromium.launch({ executablePath: process.env.E2E_CHROME, args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'tr-TR' });
const page = await ctx.newPage();
const errors = []; page.on('pageerror', (e) => errors.push(e.message));
const external = [];
page.on('request', (r) => { const u = new URL(r.url()); if (!['localhost', '127.0.0.1'].includes(u.hostname) && !u.protocol.startsWith('data') && !u.protocol.startsWith('blob')) external.push(r.url()); });
await page.addInitScript((data) => { localStorage.clear(); localStorage.setItem('luma.save.a', data); }, save);
await page.goto(process.env.E2E_URL ?? 'http://127.0.0.1:8099');
await page.getByText(/^Atölye$/).first().waitFor({ timeout: 90000 });
await page.waitForTimeout(1000);
await page.getByLabel('Ayarlar').first().click();
await page.waitForTimeout(600);
await page.mouse.move(195, 500); await page.mouse.wheel(0, 2000); await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/settings.png` });
await page.getByText('Gizlilik politikası').click(); await page.waitForTimeout(700);
await page.screenshot({ path: `${out}/privacy.png` });
await page.getByLabel('Kapat').last().click(); await page.waitForTimeout(500);
await page.getByText('Açık kaynak lisansları').click(); await page.waitForTimeout(700);
await page.screenshot({ path: `${out}/licenses.png` });
console.log('external requests:', external.length ? external : 'none');
await browser.close();
console.log(errors.length ? errors.join('\n') : 'no errors');
