"""Opaque bounds of the item and producer sprites, so board cells can fit the art itself rather
than the transparent margin around it. Run after the art changes: python3 scripts/art-tools/gen-bounds.py"""
import glob
import os

from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
rows = []
for folder in ('items', 'producers'):
    for path in sorted(glob.glob(os.path.join(ROOT, 'assets', 'art', folder, '*.png'))):
        alpha = Image.open(path).convert('RGBA').split()[3].point(lambda a: 255 if a > 10 else 0)
        box = alpha.getbbox()
        if not box:
            continue
        x0, y0, x1, y1 = box
        rows.append(f"  '{os.path.basename(path)[:-4]}': [{x0}, {y0}, {x1 - x0}, {y1 - y0}],")

with open(os.path.join(ROOT, 'src', 'art', 'bounds.generated.ts'), 'w') as f:
    f.write('// Generated by scripts/art-tools/gen-bounds.py. Do not edit by hand.\n')
    f.write('// Opaque pixel bounds [x, y, w, h] of each sprite, used to fit art to board cells.\n')
    f.write('/* eslint-disable */\n')
    f.write('export const ART_BOUNDS: Record<string, readonly [number, number, number, number]> = {\n')
    f.write('\n'.join(rows) + '\n};\n')
print(len(rows), 'sprites')
