// Production dependency license inventory: walks the runtime dependency tree from package.json
// (devDependencies excluded), reads each installed package's license field and license file, and
// writes the in-app notices (src/content/licenses.generated.ts) plus a markdown report.
//   node scripts/compliance/licenses.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = process.cwd();
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const seen = new Map();
const COPYLEFT = /\b(A?GPL|LGPL|MPL|EPL|CDDL|SSPL|EUPL|CC-BY-SA)\b/i;

function resolveDir(name, from) {
  let dir = from;
  while (true) {
    const candidate = join(dir, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return candidate;
    const up = dirname(dir);
    if (up === dir) return null;
    dir = up;
  }
}
function licenseOf(p) {
  if (typeof p.license === 'string') return p.license;
  if (p.license && p.license.type) return p.license.type;
  if (Array.isArray(p.licenses)) return p.licenses.map((l) => l.type ?? l).join(' OR ');
  return 'UNKNOWN';
}
function licenseFile(dir) {
  const f = readdirSync(dir).find((x) => /^(licen[cs]e|copying)(\.|$|-|_)/i.test(x) && !/\.(js|ts|json)$/i.test(x));
  return f ? join(dir, f) : null;
}
function walk(name, from) {
  const dir = resolveDir(name, from);
  if (!dir) return;
  const p = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const key = `${p.name}@${p.version}`;
  if (seen.has(key)) return;
  const file = licenseFile(dir);
  const repo = typeof p.repository === 'string' ? p.repository : p.repository?.url ?? p.homepage ?? '';
  seen.set(key, { name: p.name, version: p.version, license: licenseOf(p), file: file ? file.slice(root.length + 1) : null, repo: repo.replace(/^git\+/, '').replace(/\.git$/, '') });
  for (const dep of Object.keys({ ...(p.dependencies ?? {}), ...(p.optionalDependencies ?? {}) })) walk(dep, dir);
}
for (const dep of Object.keys(pkg.dependencies)) walk(dep, root);

const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const byLicense = new Map();
for (const r of rows) byLicense.set(r.license, (byLicense.get(r.license) ?? 0) + 1);
const flagged = rows.filter((r) => r.license === 'UNKNOWN' || COPYLEFT.test(r.license) || !r.file);
const md = [
  '# Üretim bağımlılıkları lisans envanteri',
  '',
  `Oluşturan: \`node scripts/compliance/licenses.mjs\` · paket sayısı: ${rows.length} (yalnız çalışma zamanı bağımlılık ağacı; geliştirme araçları hariç).`,
  '',
  '## Lisans dağılımı',
  '',
  '| Lisans | Paket |',
  '|---|---|',
  ...[...byLicense.entries()].sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`),
  '',
  '## İnceleme gerektirenler (lisans alanı yok, copyleft ifadesi veya lisans dosyası bulunamadı)',
  '',
  flagged.length ? '| Paket | Sürüm | Lisans | Lisans dosyası |\n|---|---|---|---|\n' + flagged.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.file ?? '—'} |`).join('\n') : 'Yok.',
  '',
  '## Tüm paketler',
  '',
  '| Paket | Sürüm | Lisans | Kaynak |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.repo} |`),
  '',
].join('\n');
writeFileSync(join(root, 'release-compliance/06-dependency-licenses.md'), md);
const ts = `// Generated by scripts/compliance/licenses.mjs. Do not edit by hand.
// Runtime open-source packages shipped in the app, shown in Settings → Open-source licenses.
/* eslint-disable */
export const OSS_PACKAGES: readonly { name: string; version: string; license: string; repo: string }[] = ${JSON.stringify(rows.map(({ name, version, license, repo }) => ({ name, version, license, repo })), null, 0)};
`;
writeFileSync(join(root, 'src/content/licenses.generated.ts'), ts);
console.log(`${rows.length} packages; licenses:`, Object.fromEntries(byLicense));
console.log('flagged:', flagged.map((r) => `${r.name}@${r.version} ${r.license} file=${r.file ? 'yes' : 'no'}`).join('\n  '));
